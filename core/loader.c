struct boot_info {
    uint64_t fb_addr;
    uint32_t fb_width, fb_height, fb_pitch;
    uint16_t e820_count;
    uint16_t fb_bpp;
};

static uint64_t fb_addr;
static uint32_t fb_width, fb_height, fb_pitch;
static uint32_t *fb_ptr;
static uint32_t *back_buffer;
static uint32_t fb_bpp;
static uint8_t *fb_bytes;


void put_pixel(int x, int y, uint32_t color) {
    if (x < 0 || y < 0 || (uint32_t)x >= fb_width || (uint32_t)y >= fb_height) return;
    back_buffer[y * fb_width + x] = color;
}

void draw_rect(int x, int y, int w, int h, uint32_t color) {
    for (int i = 0; i < h; i++)
        for (int j = 0; j < w; j++)
            put_pixel(x + j, y + i, color);
}

