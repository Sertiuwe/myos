void draw_char(char c, int x, int y, uint32_t color) {
    if (c < 32 || c > 126) return;
    const uint8_t *glyph = font8x16[c - 32];
    for (int row = 0; row < 16; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (1 << (7 - col))) put_pixel(x + col, y + row, color);
        }
    }
}

void draw_string(const char *str, int x, int y, uint32_t color) {
    int cx = x;
    while (*str) {
        if (*str == '\n') { cx = x; y += 16; }
        else { draw_char(*str, cx, y, color); cx += 8; }
        str++;
    }
}

void check_cpu(void) {
    uint32_t eax, ebx, ecx, edx;
    char vendor[13];
    __asm__ volatile ("cpuid" : "=a"(eax), "=b"(ebx), "=c"(ecx), "=d"(edx) : "a"(0));
    *(uint32_t*)&vendor[0] = ebx;
    *(uint32_t*)&vendor[4] = edx;
    *(uint32_t*)&vendor[8] = ecx;
    vendor[12] = 0;
    draw_string("CPU Vendor: ", 10, 50, 0xAAAAAA);
    draw_string(vendor, 130, 50, 0xFFFFFF);
    __asm__ volatile ("cpuid" : "=a"(eax), "=b"(ebx), "=c"(ecx), "=d"(edx) : "a"(0x80000001));
    if (edx & (1 << 29)) {
        draw_string("Long Mode: Supported", 10, 70, 0x00FF00);
    } else {
        draw_string("Long Mode: NOT Supported", 10, 70, 0xFF0000);
    }
}

// --- Отладочный вывод в COM1 (виден в терминале через -serial stdio) ---
static void serial_out(char c) {
    __asm__ volatile ("outb %0, %1" : : "a"(c), "Nd"((uint16_t)0x3F8));
}
static void serial_puts(const char *s) {
    while (*s) serial_out(*s++);
}
static void serial_hex64(uint64_t v) {
    serial_puts("0x");
    for (int i = 60; i >= 0; i -= 4) {
        uint32_t n = (uint32_t)((v >> i) & 0xF);
        serial_out(n < 10 ? (char)('0' + n) : (char)('A' + n - 10));
    }
}
static void serial_dec(uint32_t v) {
    char buf[12];
    int i = 0;
    if (v == 0) { serial_out('0'); return; }
    while (v) { buf[i++] = (char)('0' + (v % 10)); v /= 10; }
    while (i) serial_out(buf[--i]);
}

