uintptr_t gfx_fb_ptr(void) { return (uintptr_t)fb_ptr; }
uint32_t gfx_pitch_val(void) { return fb_pitch; }
uint8_t gfx_bpp_val(void) { return (uint8_t)fb_bpp; }
void gfx_draw_char(char c, int x, int y, uint32_t col) { draw_char(c, x, y, col); }

void gfx_flush_rows(uint32_t y0, uint32_t y1) {
    fb_lock();
    if (y1 > fb_height) y1 = fb_height;
    if (y0 >= y1) return;
    // Копируем back_buffer в реальный фреймбуфер с учётом настоящей глубины цвета.
    // pitch берём в БАЙТАХ, как его даёт VBE — никаких предположений про 4 байта.
    for (uint32_t y = y0; y < y1; y++) {
        uint8_t *row = fb_bytes + (uint64_t)y * fb_pitch;
        const uint32_t *src = back_buffer + (uint64_t)y * fb_width;
        for (uint32_t x = 0; x < fb_width; x++) {
            uint32_t c = src[x];
            uint8_t r = (uint8_t)((c >> 16) & 0xFF);
            uint8_t g = (uint8_t)((c >> 8) & 0xFF);
            uint8_t b = (uint8_t)(c & 0xFF);
            if (fb_bpp == 32) {
                row[x * 4 + 0] = b;
                row[x * 4 + 1] = g;
                row[x * 4 + 2] = r;
                row[x * 4 + 3] = 0;
            } else if (fb_bpp == 24) {
                row[x * 3 + 0] = b;
                row[x * 3 + 1] = g;
                row[x * 3 + 2] = r;
            } else if (fb_bpp == 16) {
                uint16_t v = (uint16_t)(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3));
                row[x * 2 + 0] = (uint8_t)(v & 0xFF);
                row[x * 2 + 1] = (uint8_t)(v >> 8);
            } else if (fb_bpp == 15) {
                uint16_t v = (uint16_t)(((r >> 3) << 10) | ((g >> 3) << 5) | (b >> 3));
                row[x * 2 + 0] = (uint8_t)(v & 0xFF);
                row[x * 2 + 1] = (uint8_t)(v >> 8);
            }
        }
    }
    fb_unlock();
}

void gfx_flush(void) {
    fb_lock(); gfx_flush_rows(0, fb_height);     fb_unlock();
}

void gfx_clear_all(uint32_t col) {
    fb_lock();
    uint64_t n = (uint64_t)fb_width * fb_height;
    for (uint64_t i = 0; i < n; i++) back_buffer[i] = col;
    gfx_flush();
    fb_unlock();
}

/* Partial flush: converts only the requested rectangle. Same bpp logic as
   gfx_flush_rows, but bounded in X too -- the compositor needs cheap updates. */
void gfx_flush_rect(uint32_t x0, uint32_t y0, uint32_t w, uint32_t h) {
    fb_lock();
    if (x0 >= fb_width || y0 >= fb_height || !w || !h) return;
    if (x0 + w > fb_width)  w = fb_width  - x0;
    if (y0 + h > fb_height) h = fb_height - y0;
    for (uint32_t y = y0; y < y0 + h; y++) {
        uint8_t *row = fb_bytes + (uint64_t)y * fb_pitch;
        const uint32_t *src = back_buffer + (uint64_t)y * fb_width + x0;
        if (fb_bpp == 32) {
            memcpy(row + (uint64_t)x0 * 4, src, (size_t)w * 4);
            continue;
        }
        if (fb_bpp == 24) {
            uint8_t *d = row + (uint64_t)x0 * 3;
            const uint32_t *p = src;
            uint32_t n = w;
            while (n >= 4) {
                uint32_t v0 = p[0], v1 = p[1], v2 = p[2], v3 = p[3];
                uint64_t ua = (uint64_t)(v0 & 0xFFFFFF)
                            | ((uint64_t)(v1 & 0xFFFFFF) << 24)
                            | ((uint64_t)(v2 & 0xFFFF) << 48);
                uint32_t ub = ((v2 >> 16) & 0xFF) | ((v3 & 0xFFFFFF) << 8);
                memcpy(d, &ua, 8);
                memcpy(d + 8, &ub, 4);
                d += 12; p += 4; n -= 4;
            }
            while (n--) {
                uint32_t v = *p++;
                *d++ = (uint8_t)(v & 0xFF);
                *d++ = (uint8_t)((v >> 8) & 0xFF);
                *d++ = (uint8_t)((v >> 16) & 0xFF);
            }
            continue;
        }
        for (uint32_t x = x0; x < x0 + w; x++) {
            uint32_t c = src[x - x0];
            uint8_t r = (uint8_t)((c >> 16) & 0xFF);
            uint8_t g = (uint8_t)((c >> 8) & 0xFF);
            uint8_t b = (uint8_t)(c & 0xFF);
            if (fb_bpp == 16) {
                uint16_t v = (uint16_t)(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3));
                row[x * 2 + 0] = (uint8_t)(v & 0xFF); row[x * 2 + 1] = (uint8_t)(v >> 8);
            } else if (fb_bpp == 15) {
                uint16_t v = (uint16_t)(((r >> 3) << 10) | ((g >> 3) << 5) | (b >> 3));
                row[x * 2 + 0] = (uint8_t)(v & 0xFF); row[x * 2 + 1] = (uint8_t)(v >> 8);
            }
        }
    }
    fb_unlock();
}


static void klog(const char *s) {
    serial_puts(s);
    con_puts(s);
}

__attribute__((section(".text.entry"))) void loader_main(struct boot_info *binfo) {
    /* Обнуляем .bss ПЕРВЫМ делом. Без этого после warm-reset (reboot)
       в глобалках остаются stale-указатели прошлого запуска, и kfree
       ловит double free на ещё-свободном блоке. */
    extern char __bss_start[], __bss_end[];
    memset(__bss_start, 0, (size_t)(__bss_end - __bss_start));

    fb_addr = binfo->fb_addr;
    fb_width = binfo->fb_width;
    fb_height = binfo->fb_height;
    fb_pitch = binfo->fb_pitch;
    fb_ptr = (uint32_t *)fb_addr;
    fb_bpp = binfo->fb_bpp;
    fb_bytes = (uint8_t *)fb_addr;

    serial_puts("\nK: fb=");   serial_hex64(fb_addr);
    serial_puts(" w=");         serial_dec(fb_width);
    serial_puts(" h=");         serial_dec(fb_height);
    serial_puts(" pitch=");     serial_dec(fb_pitch);
    serial_puts(" bpp=");       serial_dec(fb_bpp);
    serial_puts("\n");

    // Sanity check: если параметры мусорные — стопаемся, а не рисуем в космос
    if (fb_addr == 0 || fb_width == 0 || fb_height == 0 ||
        fb_width > 8192 || fb_height > 8192 || fb_pitch == 0) {
        serial_puts("K: BAD FB PARAMS - HALT\n");
        for (;;) __asm__ volatile ("hlt");
    }

    // 1. Инициализируем НАШ кастомный аллокатор
    kinit_heap();

    // 2. Выделяем память под задний буфер через kmalloc
    back_buffer = (uint32_t*)kmalloc(fb_width * fb_height * 4);
    if (!back_buffer) {
        // Если аллокатор сломался, мы об этом узнаем
        draw_string("KMALLOC FAILED!", 10, 10, 0xFF0000);
        while(1) __asm__ volatile ("hlt");
    }

    draw_rect(0, 0, fb_width, fb_height, 0x1E1E1E);
    draw_string("XNL Bootloader", 10, 10, 0xFFFFFF);
    draw_string("Sxnl Security X, Not Linux", 10, 26, 0x66FF99);
    draw_string("----------------", 10, 26, 0x888888);
    check_cpu();

    draw_string("VESA Mode: 1024x768x32", 10, 130, 0xAAAAAA);
    
    // Демонстрация работы аллокатора
    draw_string("Testing Custom Allocator:", 10, 170, 0xAAAAAA);
    void *p1 = kmalloc(1024);
    void *p2 = kmalloc(2048);
    
    if (p1 && p2) {
        draw_string("kmalloc(1024): SUCCESS", 10, 190, 0x00FF00);
        draw_string("kmalloc(2048): SUCCESS", 10, 210, 0x00FF00);
        
        // Тестируем освобождение и повторное выделение (проверка слияния)
        kfree(p1);
        void *p3 = kmalloc(512);
        if (p3) {
            draw_string("kfree + kmalloc(512): SUCCESS (Coalescing OK)", 10, 230, 0x00FF00);
            kfree(p3);
        }
        kfree(p2);
    } else {
        draw_string("Allocator FAILED!", 10, 190, 0xFF0000);
    }

    con_init(10, 300, fb_width - 10, fb_height - 10);
    kstdio_set_sink(klog);
    ata_init();
    bcache_init();
    myfs_mount("ata1");
    myfs_mount_vol("ata0", 2048, "/os");
    idt_init();
    pic_init();
    pit_init(1000);
    pic_unmask(0);
    pic_unmask(1);
    __asm__ volatile("sti");
    kprintf("IRQ: enabled\n");
    kernel_syscall_init();
    sched_init();
    sched_selftest();
    elf_install_demo();
    pci_init();
    ata_dma_enable();
    asset_init(8, 16);
    ga_init();
    kprintf("GA: font %ux%u (%s coords)\n",
            ga_font_w(), ga_font_h(), ga_font_cell_mode() ? "cell" : "pixel");
    mouse_init();
    pic_unmask(12);
    cursor_init((uint32_t *)(uintptr_t)gfx_fb_ptr(), gfx_width(), gfx_height(), gfx_pitch_val(), gfx_bpp_val());
    mouse_set_screen_size(gfx_width(), gfx_height());
    kheap_set_reporter(klog);
    memmap_load(binfo->e820_count);
    memmap_dump();
    kheap_selftest();
    kheap_dump();
    gfx_flush();

    con_puts("\nType 'help' for commands.\n");

    /* the shell becomes a task; main/idle just halts and waits for interrupts */
    int shell_tid = sched_spawn("shell", (void (*)(void *))shell_run, NULL, 32768);
    sched_set_base_prio(shell_tid, PRIO_NORM);
    for (;;) __asm__ volatile("hlt");

    draw_rect(10, 260, 300, 30, 0x007AFF);
    draw_string("Bootloader Ready.", 20, 268, 0xFFFFFF);

    gfx_flush();

    for (;;) __asm__ volatile ("hlt");
}
