#!/usr/bin/env python3
"""Извлекает символы из myos.elf и генерирует symbols.c"""

import subprocess
import re
import sys

ELF = "myos.elf"
OUT = "symbols.c"

# Получаем все символы через nm
try:
    nm_out = subprocess.check_output(
        ["llvm-nm", "--print-size", ELF],
        stderr=subprocess.DEVNULL
    ).decode()
except Exception as e:
    print(f"error: {e}")
    sys.exit(1)

# Парсим: address size type name
symbols = []
for line in nm_out.splitlines():
    parts = line.split()
    if len(parts) < 3:
        continue
    # формат: addr size type name  (llvm-nm --print-size)
    if len(parts) == 4:
        addr_str, size_str, type_char, name = parts
    elif len(parts) == 3:
        addr_str, type_char, name = parts
        size_str = "0"
    else:
        continue

    # Пропускаем служебные символы
    if type_char in ("u", "U", "w", "W", "N", "n"):
        continue
    # Оставляем только определённые (t, T, d, D, b, B, r, R)
    if type_char not in ("t", "T", "d", "D", "b", "B", "r", "R"):
        continue

    try:
        addr = int(addr_str, 16)
        size = int(size_str, 16)
    except ValueError:
        continue

    # Пропускаем внутренние символы (начинаются с __, .L)
    if name.startswith("__") or name.startswith(".L"):
        continue
    # Пропускаем длинные мангленные имена
    if len(name) > 40:
        continue

    symbols.append((name, addr, size, type_char))

# Сортируем по адресу
symbols.sort(key=lambda x: x[1])

# Генерируем файл
with open(OUT, "w") as f:
    f.write('/* AUTO-GENERATED by gen_symbols.py — не редактировать вручную */\n')
    f.write('#include "symbols.h"\n\n')
    f.write('const sym_entry_t g_symbols[] = {\n')
    for name, addr, size, type_char in symbols:
        f.write(f'    {{ "{name}", 0x{addr:08x}, {size} }},\n')
    f.write('};\n\n')
    f.write(f'const int g_symbol_count = sizeof(g_symbols) / sizeof(g_symbols[0]);\n')

print(f"Сгенерировано {len(symbols)} символов в {OUT}")
